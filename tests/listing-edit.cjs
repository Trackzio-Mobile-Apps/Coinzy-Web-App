const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const target = {};
const source = ts.transpileModule(fs.readFileSync('lib/marketplace/sellForm.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
vm.runInNewContext(source, { exports: target });
const listing = { price: '56', gradingScale: 'Sheldon', gradeValue: 'G-6', gradingAuthority: 'PCGS', certificationNumber: '123', strikerType: 'Proof', cleaningAlterations: ['Polished', 'Repaired'], coinCondition: 'Fine', sellerDetails: { name: 'Seller', contactEmail: 'a@example.com', phoneNumber: '12345', location: 'Delhi', bio: 'Collector', externalLinks: ['https://example.com'] } };
const form = { price: '56', contactEmail: 'a@example.com', externalLinks: ['https://example.com'], linkDraft: '', gradingScale: 'Sheldon', gradeValue: 'G-6', gradingAuthority: 'PCGS', certificationNumber: '123', strikerType: 'Proof', cleaningAlterations: 'Polished', coinCondition: 'Fine' };
let payload = target.buildSellPayload(form, { name: 'Seller', email: 'a@example.com' }, 'Coin');
assert.equal(JSON.stringify(target.buildListingUpdate(payload, listing)), '{}', 'unchanged listing does not overwrite fields');
payload = target.buildSellPayload({ ...form, price: '75', contactEmail: 'new@example.com' }, { name: 'Seller', email: 'a@example.com' }, 'Coin');
const update = target.buildListingUpdate(payload, listing);
assert.equal(update.price, 75);
assert.equal(update.sellerDetails.contactEmail, 'new@example.com');
assert.equal(update.sellerDetails.phoneNumber, '12345');
assert.equal(update.sellerDetails.location, 'Delhi');
assert.equal(update.sellerDetails.bio, 'Collector');
assert.equal(update.cleaningAlterations, undefined, 'unchanged multi-value cleaning details are preserved');
const choices = target.mergeSaleOptions(['Sheldon', 'British', 'Other (please specify)'], ['British', ' PCGS ', '']);
assert.equal(JSON.stringify(choices), JSON.stringify(['Sheldon', 'British', 'Other (please specify)', 'PCGS']), 'partial listing filters must not hide the sale form choices');
console.log('PASS: listing edits preserve metadata and sale options retain all default choices.');
